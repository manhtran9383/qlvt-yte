# -------- runtime --------
_LOCK = threading.RLock()
_LANG = "vi"          # mặc định: tiếng Việt
_CACHE = {"vi": _VI, "en": _EN}


def get_lang() -> str:
    with _LOCK:
        return _LANG


def set_lang(code: str) -> None:
    """Đặt ngôn ngữ hiện tại: 'vi' hoặc 'en'."""
    global _LANG
    code = (code or "vi").lower()
    with _LOCK:
        if code in _CACHE:
            _LANG = code


def t(key: str) -> str:
    """Dịch khóa tĩnh. Trả về key nếu không tìm thấy."""
    with _LOCK:
        return _CACHE.get(_LANG, _VI).get(key, key)


def tf(template: str, *args, **kwargs) -> str:
    """Dịch template rồi format với *args/**kwargs. Trả về template gốc nếu không tìm thấy."""
    with _LOCK:
        tpl = _CACHE.get(_LANG, _VI).get(template, template)
    try:
        return tpl.format(*args, **kwargs)
    except Exception:
        return template.format(*args, **kwargs) if args or kwargs else template


def available_languages() -> list[str]:
    return list(_CACHE.keys())